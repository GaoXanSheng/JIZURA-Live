    internal void StageToggles_Changed(object sender, RoutedEventArgs e)
    {
        if (_syncingStageToggles) return;

        _project.LegacyStageCamera = TglStageCamera.IsChecked == true;
        _project.LegacyStageTransitions = TglStageTransitions.IsChecked == true;
        _scene.CameraAffectsCharacter = TglCameraAffectsCharacter.IsChecked == true;

        if (_pipe is not null)
        {
            _pipe.StageCameraEnabled = _project.LegacyStageCamera;
            _pipe.StageTransitionsEnabled = _project.LegacyStageTransitions;
        }

        PublishDirector();
        SaveProjectNow();
        ShowStatus(L.F("StageUi.Stage.LegacyOverlayCamera", OnOff(_project.LegacyStageCamera))
                   + L.F("StageUi.Stage.LegacyOverlayTransitions", OnOff(_project.LegacyStageTransitions))
                   + L.F("StageUi.Stage.LegacyOverlayCharacterFollow", OnOff(_scene.CameraAffectsCharacter)));
    }

    private static string OnOff(bool on) => on ? L.T("StageUi.Stage.On") : L.T("StageUi.Stage.Off");

    private static bool IsUserOwned(string? source, bool locked) =>
        locked || string.Equals(source, "user", StringComparison.OrdinalIgnoreCase);

    private void AddAutoTombstone(string key)
    {
        if (string.IsNullOrWhiteSpace(key)) return;
        var layout = _project.EditorLayout ??= new EditorLayout();
        layout.DeletedAutoIds ??= new List<string>();
        if (!layout.DeletedAutoIds.Contains(key)) layout.DeletedAutoIds.Add(key);
    }

    private void SyncStageToggles()
    {
        if (!Dispatcher.CheckAccess())
        {
            Dispatcher.BeginInvoke(SyncStageToggles);
            return;
        }

        _syncingStageToggles = true;
        try
        {
            TglStageCamera.IsChecked = _project.LegacyStageCamera;
            TglStageTransitions.IsChecked = _project.LegacyStageTransitions;
            TglCameraAffectsCharacter.IsChecked = _scene.CameraAffectsCharacter;
        }
        finally
        {
            _syncingStageToggles = false;
        }
    }

    private bool _syncingCamSwitch;

    private void SyncCameraSwitchControls()
    {
        if (!Dispatcher.CheckAccess())
        {
            Dispatcher.BeginInvoke(SyncCameraSwitchControls);
            return;
        }

        var track = _project?.CameraTrack;
        var seconds = track is { SwitchSeconds: > 0 } && double.IsFinite(track.SwitchSeconds)
            ? Math.Clamp(track.SwitchSeconds, 0.1, 0.8)
            : 0.22;

        _syncingCamSwitch = true;
        try
        {
            SelectComboTag(CmbCamSwitch, string.Equals(track?.SwitchMode, "blend", StringComparison.OrdinalIgnoreCase)
                ? "blend"
                : "cut");
            SldCamBlend.Value = seconds;
            if (TblCamBlend is not null) TblCamBlend.Text = seconds.ToString("F2", CultureInfo.InvariantCulture);
        }
        finally
        {
            _syncingCamSwitch = false;
        }
    }

    internal void CmbCamSwitch_SelectionChanged(object sender, SelectionChangedEventArgs e)
    {
        if (_syncingCamSwitch || _project is null) return;
        if (CmbCamSwitch.SelectedItem is not ComboBoxItem { Tag: string mode }) return;

        var track = EnsureCameraTrack();
        if (string.Equals(track.SwitchMode, mode, StringComparison.Ordinal)) return;

        PushUndo();
        track.SwitchMode = mode;
        ApplyCameraSwitchChange(mode == "blend"
            ? L.T("StageUi.Stage.CameraSwitchBlend")
            : L.T("StageUi.Stage.CameraSwitchCut"));
    }

    internal void SldCamBlend_ValueChanged(object sender, RoutedPropertyChangedEventArgs<double> e)
    {
        if (TblCamBlend is not null) TblCamBlend.Text = e.NewValue.ToString("F2", CultureInfo.InvariantCulture);
        if (_syncingCamSwitch || _project is null) return;

        var track = EnsureCameraTrack();
        var seconds = Math.Round(Math.Clamp(e.NewValue, 0.1, 0.8), 2);
        if (Math.Abs(track.SwitchSeconds - seconds) < 1e-4) return;

        track.SwitchSeconds = seconds;
        ApplyCameraSwitchChange(L.F("StageUi.Stage.CameraBlendSeconds", seconds));
    }

    private CameraTrack EnsureCameraTrack()
    {
        var track = _project.CameraTrack ??= new CameraTrack();
        if (!double.IsFinite(track.SwitchSeconds) || track.SwitchSeconds <= 0) track.SwitchSeconds = 0.22;
        return track;
    }

    private void ApplyCameraSwitchChange(string status)
    {
        _evaluator = DirectorEvaluator.FromSaves(_project.Curves, _project.CameraTrack, _project.LayerCameraTracks);
        PublishDirector();
        _saveError = SaveProjectNow();
        ShowStatus(status);
    }

    private bool _syncingAuto;

    private string SelectedAutoStyle()
    {
        if (CmbAutoStyle.SelectedItem is ComboBoxItem { Tag: string s }) return s;
